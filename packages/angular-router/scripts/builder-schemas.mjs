// Generates the builder schemas from @angular/build's own, so they carry Angular's options, defaults
// and checks, and the CLI offers every option as a flag:
// - schemas/application.json: the application schema plus the router options from
//   router-options.json. Angular's dev server validates the build target against it.
// - schemas/serve.json: the dev-server schema with the router's poll. Its defaults equal the ones the
//   dev server applies itself when serve schedules it, so applying them first changes nothing.
// Run by the package build; tests/schema.test.mjs fails when a committed file is stale.
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const printWidth = 100;

export async function angularSchema(builder) {
  const require = createRequire(import.meta.url);
  const packageFile = require.resolve("@angular/build/package.json");
  const metadata = JSON.parse(await readFile(packageFile, "utf8"));
  const buildersFile = join(dirname(packageFile), metadata.builders);
  const builders = JSON.parse(await readFile(buildersFile, "utf8"));
  const schemaFile = join(dirname(buildersFile), builders.builders[builder].schema);
  const [schemaText, license] = await Promise.all([
    readFile(schemaFile, "utf8"),
    readFile(join(dirname(packageFile), "LICENSE"), "utf8"),
  ]);
  const { $schema, ...schema } = JSON.parse(schemaText);

  return {
    version: metadata.version,
    $schema,
    // The copied Angular schema keeps its upstream MIT notice wherever the generated file ships.
    $comment: `Generated by scripts/builder-schemas.mjs from the @angular/build ${metadata.version} ${builder} schema plus the router options. Do not edit. The @angular/build schema portions are distributed under this license:\n\n${license.trim()}`,
    schema,
  };
}

export async function applicationSchema() {
  const [angular, routerText] = await Promise.all([
    angularSchema("application"),
    readFile(new URL("router-options.json", import.meta.url), "utf8"),
  ]);
  const router = JSON.parse(routerText);

  for (const key of Object.keys(router.properties)) {
    if (Object.hasOwn(angular.schema.properties, key)) {
      throw new Error(
        `@angular/build ${angular.version} now has an application option named ${key}`,
      );
    }
  }

  const schema = {
    $schema: angular.$schema,
    $comment: angular.$comment,
    ...angular.schema,
    properties: { ...router.properties, ...angular.schema.properties },
    required: [...router.required, ...angular.schema.required],
  };

  return `${format(schema, "")}\n`;
}

export async function serveSchema() {
  const angular = await angularSchema("dev-server");
  const properties = { ...angular.schema.properties };

  // Serve forwards poll and buildTarget to the dev server, so both must remain Angular options.
  for (const key of ["buildTarget", "poll"]) {
    if (!Object.hasOwn(properties, key)) {
      throw new Error(`@angular/build ${angular.version} no longer has a dev-server option ${key}`);
    }
  }

  properties.buildTarget = {
    ...properties.buildTarget,
    description:
      "A target using @loozo/angular-router:application, as project:target[:configuration]. Router options come from it.",
  };
  properties.poll = {
    description:
      "Watch by polling every this many milliseconds. Defaults to 1000 when omitted. false adds no default, so Angular's own configuration applies, including a poll on the build target.",
    oneOf: [{ type: "number", exclusiveMinimum: 0 }, { const: false }],
  };

  const schema = {
    $schema: angular.$schema,
    $comment: angular.$comment,
    ...angular.schema,
    properties,
  };

  return `${format(schema, "")}\n`;
}

// JSON as the repository formatter prints it: objects expanded, primitive arrays inline when they fit.
function format(value, indent, prefix = "", suffix = "") {
  if (value === null || typeof value !== "object") {
    return JSON.stringify(value);
  }

  const inner = `${indent}  `;
  const lines = [];

  if (Array.isArray(value)) {
    if (value.length === 0) {
      return "[]";
    }

    const items = [];
    let primitive = true;

    for (const item of value) {
      items.push(JSON.stringify(item));
      primitive &&= item === null || typeof item !== "object";
    }

    const inline = `[${items.join(", ")}]`;

    if (primitive && indent.length + prefix.length + inline.length + suffix.length <= printWidth) {
      return inline;
    }

    for (const item of value) {
      lines.push(`${inner}${format(item, inner)}`);
    }

    return `[\n${lines.join(",\n")}\n${indent}]`;
  }

  const entries = Object.entries(value);

  if (entries.length === 0) {
    return "{}";
  }

  for (const [index, [key, item]] of entries.entries()) {
    const property = `${JSON.stringify(key)}: `;
    let comma = ",";

    if (index === entries.length - 1) {
      comma = "";
    }

    lines.push(`${inner}${property}${format(item, inner, property, comma)}`);
  }

  return `{\n${lines.join(",\n")}\n${indent}}`;
}

if (import.meta.main) {
  const [application, serve] = await Promise.all([applicationSchema(), serveSchema()]);

  await Promise.all([
    writeFile(fileURLToPath(new URL("../schemas/application.json", import.meta.url)), application),
    writeFile(fileURLToPath(new URL("../schemas/serve.json", import.meta.url)), serve),
  ]);
}
