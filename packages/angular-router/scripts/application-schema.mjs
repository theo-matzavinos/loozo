// Generates schemas/application.json: @angular/build's application schema plus the router options
// from router-options.json. Angular's dev server validates the build target against this schema, so
// it must carry Angular's defaults and checks. Run by the package build; tests/schema.test.mjs fails
// when the committed file is stale.
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const printWidth = 100;

export async function applicationSchema() {
  const require = createRequire(import.meta.url);
  const packageFile = require.resolve("@angular/build/package.json");
  const metadata = JSON.parse(await readFile(packageFile, "utf8"));
  const buildersFile = join(dirname(packageFile), metadata.builders);
  const builders = JSON.parse(await readFile(buildersFile, "utf8"));
  const schemaFile = join(dirname(buildersFile), builders.builders.application.schema);
  const [angularText, routerText, angularLicense] = await Promise.all([
    readFile(schemaFile, "utf8"),
    readFile(new URL("router-options.json", import.meta.url), "utf8"),
    readFile(join(dirname(packageFile), "LICENSE"), "utf8"),
  ]);
  const { $schema, ...angular } = JSON.parse(angularText);
  const router = JSON.parse(routerText);

  for (const key of Object.keys(router.properties)) {
    if (Object.hasOwn(angular.properties, key)) {
      throw new Error(
        `@angular/build ${metadata.version} now has an application option named ${key}`,
      );
    }
  }

  const schema = {
    $schema,
    // The copied Angular schema keeps its upstream MIT notice wherever this file ships.
    $comment: `Generated by scripts/application-schema.mjs from the @angular/build ${metadata.version} application schema plus the router options. Do not edit. The @angular/build schema portions are distributed under this license:\n\n${angularLicense.trim()}`,
    ...angular,
    properties: { ...router.properties, ...angular.properties },
    required: [...router.required, ...angular.required],
  };

  return `${format(schema, "")}\n`;
}

// JSON as the repository formatter prints it: objects expanded, primitive arrays inline when they fit.
function format(value, indent, prefix = "", suffix = "") {
  if (value === null || typeof value !== "object") {
    return JSON.stringify(value);
  }

  const inner = `${indent}  `;
  const lines = [];

  if (Array.isArray(value)) {
    if (value.length === 0) {
      return "[]";
    }

    const items = [];
    let primitive = true;

    for (const item of value) {
      items.push(JSON.stringify(item));
      primitive &&= item === null || typeof item !== "object";
    }

    const inline = `[${items.join(", ")}]`;

    if (primitive && indent.length + prefix.length + inline.length + suffix.length <= printWidth) {
      return inline;
    }

    for (const item of value) {
      lines.push(`${inner}${format(item, inner)}`);
    }

    return `[\n${lines.join(",\n")}\n${indent}]`;
  }

  const entries = Object.entries(value);

  if (entries.length === 0) {
    return "{}";
  }

  for (const [index, [key, item]] of entries.entries()) {
    const property = `${JSON.stringify(key)}: `;
    let comma = ",";

    if (index === entries.length - 1) {
      comma = "";
    }

    lines.push(`${inner}${property}${format(item, inner, property, comma)}`);
  }

  return `{\n${lines.join(",\n")}\n${indent}}`;
}

if (import.meta.main) {
  const target = fileURLToPath(new URL("../schemas/application.json", import.meta.url));

  await writeFile(target, await applicationSchema());
}
