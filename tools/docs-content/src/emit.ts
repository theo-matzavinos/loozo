import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import type { BuiltContent } from "./content.ts";

const header = "// Generated by @loozo/docs-content. Do not edit.\n";

/**
 * Writes `model.generated.ts`, `index.generated.ts`, `demos.generated.ts` and one
 * `<slug>.generated.ts` per package.
 */
export async function writeContent(outDir: string, { contents, demos }: BuiltContent) {
  const model = await readFile(new URL("./model.ts", import.meta.url), "utf8");
  const files = new Map<string, string>([["model.generated.ts", model]]);
  const slugs: string[] = [];
  const summaries: object[] = [];
  let loaders = "";

  for (const content of contents) {
    const slug = JSON.stringify(content.slug);

    slugs.push(slug);
    summaries.push({
      name: content.name,
      slug: content.slug,
      version: content.version,
      description: content.description,
    });
    loaders += `  ${slug}: () => import("./${content.slug}.generated.js"),\n`;
    files.set(
      `${content.slug}.generated.ts`,
      `${header}import type { PackageContent } from "./model.generated.js";\n\n` +
        `export const content: PackageContent = ${JSON.stringify(content, null, 2)};\n`,
    );
  }

  files.set(
    "index.generated.ts",
    `${header}import type { PackageContent, PackageSummary } from "./model.generated.js";\n\n` +
      `export const packageSlugs = [${slugs.join(", ")}] as const;\n\n` +
      `export type PackageSlug = (typeof packageSlugs)[number];\n\n` +
      `export interface GeneratedPackageSummary extends PackageSummary {\n` +
      `  readonly slug: PackageSlug;\n` +
      `}\n\n` +
      `export const packages: readonly GeneratedPackageSummary[] = ` +
      `${JSON.stringify(summaries, null, 2)};\n\n` +
      `const loaders: Record<PackageSlug, () => Promise<{ readonly content: PackageContent }>> = {\n` +
      `${loaders}};\n\n` +
      `export async function loadPackage(slug: PackageSlug): Promise<PackageContent> {\n` +
      `  const module = await loaders[slug]();\n\n` +
      `  return module.content;\n` +
      `}\n`,
  );

  let demoLoaders = "";

  for (const demo of demos) {
    // The app's bundler resolves the snippet's .ts source from an extensionless import.
    const specifier = relative(outDir, demo.file).split(sep).join("/").replace(/\.ts$/, "");

    demoLoaders +=
      `  ${JSON.stringify(demo.id)}: () =>\n` +
      `    import(${JSON.stringify(specifier)}).then((module) => module.${demo.exportName}),\n`;
  }

  files.set(
    "demos.generated.ts",
    `${header}import type { Type } from "@angular/core";\n\n` +
      `/** Lazy loaders of the components that guide pages run, by demo id. */\n` +
      `export const demos: Record<string, () => Promise<Type<unknown>>> = {\n` +
      `${demoLoaders}};\n`,
  );

  await mkdir(outDir, { recursive: true });

  const writes: Promise<void>[] = [];

  for (const [name, text] of files) {
    writes.push(writeFile(join(outDir, name), text));
  }

  await Promise.all(writes);
}
